# Installs ZeroTier, Python venv, proxyscript. Does not start the proxy.
$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

function Import-ProxyPiCommon {
    $raw = if ($env:PROXYPI_REPO_URL) { $env:PROXYPI_REPO_URL.TrimEnd("/") } else { "https://raw.githubusercontent.com/conthegreat/proxypi-script/main" }
    if ($PSScriptRoot) {
        $local = Join-Path $PSScriptRoot "common.ps1"
        if (Test-Path $local) { . $local; return }
    }
    $tmp = Join-Path $env:TEMP "proxypi-common.ps1"
    Invoke-WebRequest -Uri "$raw/install/windows/common.ps1" -OutFile $tmp -UseBasicParsing
    . $tmp
}

Import-ProxyPiCommon
Require-Admin
Require-Windows64

$RepoRaw = Get-RepoRaw
$InstallDir = Get-InstallDir
$NetworkId = "664bb06760e47198"
$PythonInstallerUrl = "https://www.python.org/ftp/python/3.12.10/python-3.12.10-amd64.exe"
$ZeroTierMsiUrl = "https://download.zerotier.com/dist/ZeroTier%20One.msi"

function Install-PythonIfMissing {
    $existing = Get-PythonExe
    if ($existing) {
        Write-Info "Python found: $existing"
        return $existing
    }
    Write-Info "Installing Python 3.12 (all users, with pip)"
    $exe = Join-Path $env:TEMP "python-3.12.10-amd64.exe"
    Download-File $PythonInstallerUrl $exe
    $args = "/quiet InstallAllUsers=1 PrependPath=1 Include_pip=1 Include_test=0 Include_launcher=1 SimpleInstall=1"
    $p = Start-Process -FilePath $exe -ArgumentList $args -Wait -PassThru
    if ($p.ExitCode -ne 0) { Write-Die "Python installer failed with exit code $($p.ExitCode)" }
    $py = Get-PythonExe
    if (-not $py) {
        $fallback = Join-Path ${env:ProgramFiles} "Python312\python.exe"
        if (Test-Path $fallback) { $py = $fallback }
    }
    if (-not $py) { Write-Die "Python installed but python.exe was not found. Sign out and run join again." }
    Write-Ok "Python installed: $py"
    return $py
}

function Install-ZeroTierIfMissing {
    if (Get-ZeroTierCli) {
        Write-Info "ZeroTier already installed"
    } else {
        Write-Info "Installing ZeroTier"
        $msi = Join-Path $env:TEMP "ZeroTierOne.msi"
        Download-File $ZeroTierMsiUrl $msi
        $p = Start-Process -FilePath "msiexec.exe" -ArgumentList "/i `"$msi`" /qn /norestart" -Wait -PassThru
        if ($p.ExitCode -ne 0 -and $p.ExitCode -ne 3010) {
            Write-Die "ZeroTier MSI failed with exit code $($p.ExitCode)"
        }
        Start-Sleep -Seconds 3
    }
    $svc = Get-Service -Name "ZeroTierOneService" -ErrorAction SilentlyContinue
    if (-not $svc) { Write-Die "ZeroTier service was not found after install." }
    if ($svc.Status -ne "Running") {
        Start-Service "ZeroTierOneService"
        Start-Sleep -Seconds 4
    }
    if (-not (Get-ZeroTierCli)) { Write-Die "ZeroTier CLI still not found after install." }
}

function Join-ZeroTierNetwork {
    Write-Info "Joining ZeroTier network $NetworkId"
    $r = Invoke-ZeroTier "join" $NetworkId
    if ($r.Text) { Write-Host $r.Text.Trim() }
    Start-Sleep -Seconds 3
}

function Install-ProxyFiles {
    Write-Info "Downloading proxy files to $InstallDir"
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
    New-Item -ItemType Directory -Path (Join-Path $InstallDir "logs") -Force | Out-Null
    New-Item -ItemType Directory -Path (Join-Path $InstallDir "bin") -Force | Out-Null
    Download-File "$RepoRaw/proxyscript.py" (Join-Path $InstallDir "proxyscript.py")
    Download-File "$RepoRaw/requirements.txt" (Join-Path $InstallDir "requirements.txt")
    Download-File "$RepoRaw/install/config.defaults" (Join-Path $InstallDir "config.defaults")
    Download-File "$RepoRaw/install/windows/run-proxy.ps1" (Join-Path $InstallDir "run-proxy.ps1")
    Download-File "$RepoRaw/install/windows/heartbeat.ps1" (Join-Path $InstallDir "heartbeat.ps1")
    Download-File "$RepoRaw/install/windows/common.ps1" (Join-Path $InstallDir "common.ps1")
}

function Install-Venv([string]$PythonExe) {
    $venv = Join-Path $InstallDir "venv"
    Write-Info "Creating Python virtual environment"
    & $PythonExe -m venv $venv
    if ($LASTEXITCODE -ne 0) { Write-Die "python -m venv failed" }
    $pip = Join-Path $venv "Scripts\pip.exe"
    $venvPy = Join-Path $venv "Scripts\python.exe"
    & $venvPy -m pip install --upgrade pip -q
    & $pip install -r (Join-Path $InstallDir "requirements.txt") -q
    if ($LASTEXITCODE -ne 0) { Write-Die "pip install failed (need internet for pyrad)" }
    Write-Ok "venv ready: $venvPy"
}

function Write-NodeInfo {
    $nodeId = Get-ZeroTierNodeId
    $ztIp = Get-ZeroTierIp
    $hostname = $env:COMPUTERNAME
    $info = Join-Path $InstallDir "node-info.env"
    @"
# Generated by ProxyPi Windows setup $(Get-Date -Format o)
HOSTNAME=$hostname
ZT_NODE_ID=$nodeId
ZEROTIER_NODE_ID=$nodeId
ZT_IP=$(if ($ztIp) { $ztIp } else { "pending" })
INSTALL_DIR=$InstallDir
SERVICE_NAME=ProxyPi
STATUS=awaiting_activation
"@ | Set-Content -Path $info -Encoding ASCII
    Protect-SecretFile $info
    return @{ NodeId = $nodeId; ZtIp = $ztIp; Hostname = $hostname }
}

